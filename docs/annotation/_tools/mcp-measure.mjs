// MCP SDK 生产源文件测量：文件数/行数/800+ 文件/注释行÷代码行中位数/生成物识别。
// 用法：node mcp-measure.mjs [--json out.json]
import fs from 'node:fs';
import path from 'node:path';

const repo = 'D:/code/opensource/mcp-sdk';
const isTest = (rel) =>
  /[\\/](test|tests|__tests__)[\\/]/.test(rel) || /\.(test|spec)\.[cm]?tsx?$/.test(rel);
const isExamples = (rel) => /\.examples\.[cm]?tsx?$/.test(rel);
const isConfig = (rel) => /(^|[\\/])(tsdown|vitest|typedoc|eslint)[^\\/]*\.config\.[cm]?ts$/.test(rel);

function walk(dir, out = []) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) {
      if (e.name === 'node_modules' || e.name === 'dist') continue;
      walk(p, out);
    } else if (/\.(ts|tsx|mts|cts)$/.test(e.name)) out.push(p);
  }
  return out;
}

function measure(text) {
  const lines = text.split('\n');
  if (lines.length && lines[lines.length - 1] === '') lines.pop();
  let total = 0,
    blank = 0,
    comment = 0;
  let inBlock = false;
  for (const raw of lines) {
    total++;
    const t = raw.trim();
    if (inBlock) {
      comment++;
      if (t.includes('*/')) inBlock = false;
      continue;
    }
    if (!t) {
      blank++;
    } else if (t.startsWith('//')) {
      comment++;
    } else if (t.startsWith('/*')) {
      comment++;
      if (!t.includes('*/')) inBlock = true;
    } else if (t.startsWith('*')) {
      comment++;
      if (t.includes('*/')) inBlock = false;
    } else {
      // 行尾注释不算注释行
    }
  }
  return { total, blank, comment, code: total - blank - comment };
}

const roots = ['packages'];
const all = [];
for (const f of walk(path.join(repo, roots[0]))) {
  const rel = path.relative(repo, f).replace(/\\/g, '/');
  if (isTest(rel) || isExamples(rel) || isConfig(rel)) continue;
  if (!/\/src\//.test(rel)) continue;
  const text = fs.readFileSync(f, 'utf8');
  const m = measure(text);
  const head = text.slice(0, 800).toLowerCase();
  const generated = /automatically generated|do not edit|autogenerated|@generated/.test(head);
  all.push({ rel, ...m, generated, density: m.code ? m.comment / m.code : 1 });
}

const prod = all.filter((x) => !x.generated);
const gen = all.filter((x) => x.generated);
const dens = prod.map((x) => x.density).sort((a, b) => a - b);
const median = dens.length ? dens[Math.floor(dens.length / 2)] : 0;
const below30 = prod.filter((x) => x.density < 0.3);
const needLines = below30.reduce(
  (s, x) => s + Math.max(0, Math.ceil(x.code * 0.3) - x.comment),
  0,
);

const sum = (arr, k) => arr.reduce((s, x) => s + x[k], 0);
console.log('files(prod)=' + prod.length + ' lines=' + sum(prod, 'total') + ' code=' + sum(prod, 'code') + ' comment=' + sum(prod, 'comment'));
console.log('files(generated)=' + gen.length + ' lines=' + sum(gen, 'total'));
console.log('files>800=' + prod.filter((x) => x.total > 800).length);
console.log('medianCommentDivCode=' + (median * 100).toFixed(2) + '%');
console.log('overallCommentDivCode=' + ((sum(prod, 'comment') / sum(prod, 'code')) * 100).toFixed(2) + '%');
console.log('below30=' + below30.length + ' needLines=' + needLines);

const byPkg = {};
for (const x of prod) {
  const pkg = x.rel.split('/').slice(0, 2).join('/');
  byPkg[pkg] ??= { files: 0, lines: 0, over800: 0 };
  byPkg[pkg].files++;
  byPkg[pkg].lines += x.total;
  if (x.total > 800) byPkg[pkg].over800++;
}
console.log('--- by package ---');
for (const [k, v] of Object.entries(byPkg).sort()) console.log(`${k}\tfiles=${v.files}\tlines=${v.lines}\tover800=${v.over800}`);

console.log('--- generated ---');
for (const g of gen) console.log(`${g.rel}\t${g.total}`);

const outIdx = process.argv.indexOf('--json');
if (outIdx > 0 && process.argv[outIdx + 1]) {
  fs.writeFileSync(
    process.argv[outIdx + 1],
    JSON.stringify({ repo, prod, gen, median, needLines }, null, 1),
  );
  console.log('json -> ' + process.argv[outIdx + 1]);
}
