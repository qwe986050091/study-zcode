// MCP Python SDK 生产源文件测量：# 整行注释 ÷ 代码行；docstring 按代码行（与 DEEP-SPEC 5.1 一致）。
// 用法：node mcp-py-measure.mjs [--json out.json]
import fs from 'node:fs';
import path from 'node:path';

const repo = 'D:/code/opensource/mcp-python-sdk';
const rootDir = path.join(repo, 'src/mcp');
const isTest = (rel) =>
  /[\\/](tests?|__pycache__)[\\/]/.test(rel) || /(^|[\\/])test_[^\\/]*\.py$/.test(rel) || /_test\.py$/.test(rel);
const isExamples = (rel) => /[\\/]examples?[\\/]/.test(rel) || /(^|[\\/])example_[^\\/]*\.py$/.test(rel);

function walk(dir, out = []) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) {
      if (e.name === '__pycache__' || e.name === 'node_modules' || e.name === 'dist') continue;
      walk(p, out);
    } else if (e.name.endsWith('.py')) out.push(p);
  }
  return out;
}

function measure(text) {
  const lines = text.split('\n');
  if (lines.length && lines[lines.length - 1] === '') lines.pop();
  let total = 0,
    blank = 0,
    comment = 0;
  for (const raw of lines) {
    total++;
    const t = raw.trim();
    if (!t) blank++;
    else if (t.startsWith('#')) comment++;
  }
  return { total, blank, comment, code: total - blank - comment };
}

const all = [];
for (const f of walk(rootDir)) {
  const rel = path.relative(repo, f).replace(/\\/g, '/');
  if (isTest(rel) || isExamples(rel)) continue;
  const text = fs.readFileSync(f, 'utf8');
  const m = measure(text);
  const head = text.slice(0, 1000).toLowerCase();
  const generated = /automatically generated|do not edit|autogenerated|@generated/.test(head);
  all.push({ rel, ...m, generated, density: m.code ? m.comment / m.code : 1 });
}

const prod = all.filter((x) => !x.generated);
const gen = all.filter((x) => x.generated);
const dens = prod.map((x) => x.density).sort((a, b) => a - b);
const median = dens.length ? dens[Math.floor(dens.length / 2)] : 0;
const below30 = prod.filter((x) => x.density < 0.3);
const need30 = below30.reduce((s, x) => s + Math.max(0, Math.ceil(x.code * 0.3) - x.comment), 0);
const need32 = below30.reduce((s, x) => s + Math.max(0, Math.ceil(x.code * 0.32) - x.comment), 0);
const sum = (arr, k) => arr.reduce((s, x) => s + x[k], 0);

console.log('files(prod)=' + prod.length + ' lines=' + sum(prod, 'total') + ' code=' + sum(prod, 'code') + ' comment=' + sum(prod, 'comment'));
console.log('files(generated)=' + gen.length + ' lines=' + sum(gen, 'total'));
console.log('files>800=' + prod.filter((x) => x.total > 800).length);
console.log('medianCommentDivCode=' + (median * 100).toFixed(2) + '%');
console.log('overallCommentDivCode=' + ((sum(prod, 'comment') / sum(prod, 'code')) * 100).toFixed(2) + '%');
console.log('below30=' + below30.length + ' need30=' + need30 + ' need32=' + need32);

const byPkg = {};
for (const x of prod) {
  const pkg = x.rel.split('/').slice(0, 3).join('/');
  byPkg[pkg] ??= { files: 0, lines: 0, over800: 0, need: 0 };
  byPkg[pkg].files++;
  byPkg[pkg].lines += x.total;
  if (x.total > 800) byPkg[pkg].over800++;
}
console.log('--- by package (need@32) ---');
for (const [k, v] of Object.entries(byPkg).sort()) {
  const b = below30.filter((x) => x.rel.startsWith(k + '/'));
  const n = b.reduce((s, x) => s + Math.max(0, Math.ceil(x.code * 0.32) - x.comment), 0);
  console.log(`${k}\tfiles=${v.files}\tlines=${v.lines}\tover800=${v.over800}\tbelow30=${b.length}\tneed=${n}`);
}
console.log('--- generated ---');
for (const g of gen) console.log(`${g.rel}\t${g.total}`);

const outIdx = process.argv.indexOf('--json');
if (outIdx > 0 && process.argv[outIdx + 1]) {
  fs.writeFileSync(process.argv[outIdx + 1], JSON.stringify({ repo, prod, gen, median, need30, need32 }, null, 1));
  console.log('json -> ' + process.argv[outIdx + 1]);
}
